"""QB-05: pressure his line allows vs pressure the opponent's defense generates.

Pre-registration: docs/research/blocks/QB-05.md. Shared builders:
_p4_participation_priors.py (participation priors, package P4).
"""
from __future__ import annotations

import pandas as pd

import _common as C
import _p4_participation_priors as P

ID = "QB-05"
TITLE = "Team pressure: allowed by his line vs generated by the opponent"
COLUMNS = {"QB": ["own_press_allowed_prior", "own_sackhit_allowed_std",
                  "opp_press_gen_prior", "opp_sackhit_gen_std"]}


def build(ctx):
    keys = ctx.keys_for("QB")[["season", "week", "gsis_id", "team", "opponent"]]
    seasons = sorted({int(s) for s in keys["season"]})
    prior = [s - 1 for s in seasons]
    drop = P.dropbacks(ctx, sorted(set(seasons) | set(prior)))
    press = P.team_pressure(P.charted(ctx, drop, prior))
    sides = pd.concat([keys[["season", "week", "team"]],
                       keys[["season", "week", "opponent"]].rename(columns={"opponent": "team"})])
    std = P.team_sackhit_as_of(drop.loc[drop["season"].isin(seasons)], sides)

    r = keys.merge(std[["season", "week", "team", "sackhit_allowed_std"]].rename(
        columns={"sackhit_allowed_std": "own_sackhit_allowed_std"}),
        on=["season", "week", "team"], how="left")
    r = r.merge(std[["season", "week", "team", "sackhit_gen_std"]].rename(
        columns={"team": "opponent", "sackhit_gen_std": "opp_sackhit_gen_std"}),
        on=["season", "week", "opponent"], how="left")
    r = C.prior_season(r, press.rename(columns={"press_allowed": "own_press_allowed_prior"}),
                       ["team"], ["own_press_allowed_prior"])
    r = C.prior_season(r, press.rename(columns={"team": "opponent",
                                                "press_gen": "opp_press_gen_prior"}),
                       ["opponent"], ["opp_press_gen_prior"])
    return r[["season", "week", "gsis_id", *COLUMNS["QB"]]]
